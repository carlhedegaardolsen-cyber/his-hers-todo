-- Adds a table for custom calendar events. Existing todos are untouched.
CREATE TABLE IF NOT EXISTS public.calendar_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  event_date date NOT NULL,
  event_time time,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.calendar_events DISABLE ROW LEVEL SECURITY;
GRANT ALL ON public.calendar_events TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.calendar_events_id_seq TO anon, authenticated;
NOTIFY pgrst, 'reload schema';
